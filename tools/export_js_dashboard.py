"""Feed the JavaScript interface (phase 3 bonus) from the application artefacts.

    python tools/export_js_dashboard.py

Writes 03_power_bi/javascript_bonus/data.js: the same aggregates as the Streamlit application,
in a JavaScript variable, so that index.html opens with a simple double-click.
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ARTIFACTS = ROOT / "05_web_app" / "artifacts"
OUTPUT = ROOT / "03_power_bi" / "javascript_bonus" / "data.js"

kpi = json.loads((ARTIFACTS / "kpi_summary.json").read_text(encoding="utf-8"))
forecast = json.loads((ARTIFACTS / "kpi_forecast.json").read_text(encoding="utf-8"))
payload = {"kpi": kpi, "forecast": {"history": forecast["history"]}}
OUTPUT.write_text(
    "// File generated by tools/export_js_dashboard.py — aggregates only, no customer row.\n"
    "window.VIGIE_DATA = " + json.dumps(payload, ensure_ascii=False, separators=(",", ":")) + ";\n",
    encoding="utf-8")
print(f"written: {OUTPUT.relative_to(ROOT)} ({OUTPUT.stat().st_size / 1024:.0f} KB)")
