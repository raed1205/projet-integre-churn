"""Generate ``04_machine_learning/comparison.md`` from the results saved by the notebooks.

    python 04_machine_learning/src/comparison_report.py

No figure is typed by hand: everything comes from ``results/*.json``.
"""

from __future__ import annotations

import json
import sys
from decimal import ROUND_HALF_UP, Decimal
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from vigie import config  # noqa: E402


def num(x: float, d: int = 3) -> str:
    """Round half up: avoids the surprises of binary double rounding."""
    return str(Decimal(repr(x)).quantize(Decimal(1).scaleb(-d), rounding=ROUND_HALF_UP))


def pct(x: float, d: int = 1) -> str:
    return f"{num(100 * x, d)}%"


def main() -> None:
    churn = json.loads((config.ML_RESULTS / "churn_ml.json").read_text(encoding="utf-8"))
    fc = json.loads((config.ML_RESULTS / "kpi_forecast.json").read_text(encoding="utf-8"))
    L = [
        "# Model comparison tables — VIGIE · Group BI 5",
        "",
        "> File generated by `src/comparison_report.py` from `results/*.json` (themselves written by the notebooks).",
        "> No figure is typed by hand.  ",
        f"> Source file: `data_churn.csv`, SHA-256 `{churn['source_sha256'][:16]}…`",
        "",
        "## 1. Churn prediction (customer grain, test set: 47,856 customers)",
        "",
        "Split per customer (`GroupShuffleSplit`, 70 / 15 / 15). Decision threshold chosen on the validation set (highest F1).",
        "",
        "| Model | ROC-AUC | PR-AUC | Precision | Recall | F1 | Accuracy | Brier | Threshold |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for name, m in churn["model_comparison"].items():
        bold = "**" if "kept" in name else ""
        L.append(f"| {bold}{name}{bold} | {num(m['ROC-AUC'])} | {num(m['PR-AUC'])} | {num(m['Precision'])} | {num(m['Recall'])} | "
                 f"{num(m['F1'])} | {num(m['Accuracy'])} | {num(m['Brier'])} | {num(m['Threshold'], 2)} |")
    L += ["", "**Confusion matrices (test set)**", "",
          "| Model | True positives | False positives | False negatives | True negatives |", "|---|---:|---:|---:|---:|"]
    for name, m in churn["confusion_matrices"].items():
        L.append(f"| {name} | {m['TP']:,} | {m['FP']:,} | {m['FN']:,} | {m['TN']:,} |")
    h = churn["hyperparameters"]
    s = churn["roc_auc_stability"]
    L += ["", "**Model kept: tuned XGBoost.** Hyperparameters (random search, cross-validation per customer): "
          + ", ".join(f"`{k}` = {v:g}" for k, v in sorted(h.items())) + ".", "",
          f"Stability (ROC-AUC): training {num(s['Training'])} · validation {num(s['Validation'])} · test {num(s['Test'])}.",
          "", "### Target leakage check", "", "| Model | ROC-AUC on the test set |", "|---|---:|"]
    for name, v in churn["leakage_demonstration"].items():
        L.append(f"| {name} | {num(v)} |")
    L += ["", "Columns excluded for leakage (AUC of the single \"value is missing\" flag ≥ 0.80):", "",
          "| Column | % blank if active | % blank if closed | Blank AUC | Verdict |", "|---|---:|---:|---:|---|"]
    for a in churn["leakage_audit"]:
        if a["Blank AUC"] >= 0.6:
            L.append(f"| `{a['Variable']}` | {num(a['% blank if active'], 1)} | {num(a['% blank if closed'], 1)} | "
                     f"{num(a['Blank AUC'])} | {a['Verdict']} |")
    L += ["", "`PRODUCT_STATUS` is excluded as well: it is not its blank but its values (`CLOSE`, `PENDING.CLOSURE`, "
          "`UNAUTH`) that point to the closure.", "", "### Sensitivity analysis (same XGBoost, features removed or added)", "",
          "| Scenario | Columns | ROC-AUC | PR-AUC | ROC-AUC gap |", "|---|---:|---:|---:|---:|"]
    for name, m in churn["sensitivity"].items():
        sign = "+" if m["ROC-AUC gap"] >= 0 else "−"
        L.append(f"| {name} | {int(m['Columns'])} | {num(m['ROC-AUC'])} | {num(m['PR-AUC'])} | {sign}{num(abs(m['ROC-AUC gap']))} |")
    L += ["", "### Feature importance", "", "| Feature | XGBoost gain | SHAP (share) |", "|---|---:|---:|"]
    for i in churn["importance"]:
        L.append(f"| {i['Feature']} | {pct(i['Gain (share)'])} | {pct(i['SHAP (share)'])} |")
    L += ["", "### Gains curve and risk levels", "",
          "| Customers targeted (decreasing scores) | Departures captured | Churn rate in the target | Lift |", "|---:|---:|---:|---:|"]
    for g in churn["gains"]:
        L.append(f"| {pct(g['Customers targeted'], 0)} | {pct(g['Departures captured'])} | {pct(g['Churn rate in the target'])} | {num(g['Lift'], 2)} |")
    L += ["", "| Risk level | Test customers | Observed churn rate |", "|---|---:|---:|"]
    for lv in churn["risk_levels"]:
        L.append(f"| {lv['level']} | {lv['test_customers']:,} | {pct(lv['observed_rate'])} |")

    for key, title in (("weekly_closures", "2. KPI forecast — account closures per week"),
                       ("weekly_customers_lost", "3. Bonus — second KPI: customers lost per week")):
        r = fc[key]
        d = r["split"]
        naive = next(row for row in r["comparison"] if row["Model"].startswith("Naive"))
        L += ["", f"## {title}", "",
              f"Series corrected for mass operations · {d['weeks']} weeks · training {d['train']} · validation {d['validation']} · "
              f"test {d['test']} (from {d['test_start']} to {d['test_end']}) · {d['window']}-week window · one-step-ahead forecast.", "",
              "| Model | Type | MAE | RMSE | MAE vs naive | RMSE vs naive |", "|---|---|---:|---:|---:|---:|"]
        for row in sorted(r["comparison"], key=lambda x: x["MAE"]):
            spread = row.get("MAE std")
            extra = f" (± {num(spread, 1)} over 3 seeds)" if isinstance(spread, float) and spread == spread else ""
            L.append(f"| {row['Model']} | {row['Type']} | {num(row['MAE'], 1)}{extra} | {num(row['RMSE'], 1)} | "
                     f"{100 * (row['MAE'] / naive['MAE'] - 1):+.0f}% | {100 * (row['RMSE'] / naive['RMSE'] - 1):+.0f}% |")
    L += ["", "**Reading.** The LSTM clearly reduces the error of the naive forecast and does better than the simple RNN, "
          "ARIMA and the moving average. It does not beat the moving median on account closures; it has the best MAE on "
          "customers lost. MAPE is not used: it is not defined on zero weeks.", ""]
    (ROOT / "04_machine_learning" / "comparison.md").write_text("\n".join(L), encoding="utf-8")
    print("written: 04_machine_learning/comparison.md")


if __name__ == "__main__":
    main()
